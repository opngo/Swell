export type IconName = keyof typeof ICONS;

export type SwIconProps = SVGProps<SVGSVGElement> & {
  name: IconName;
  /** px size; defaults to 18 per §11 (18 / 20 / 24 are the sanctioned steps). */
  size?: number;
  strokeWidth?: number;
};

/**
 * Single entry point for icons: `<SwIcon name="layers" size={18} />`.
 * Keeps strokeWidth consistent at 1.5 and colour at currentColor.
 */
export function SwIcon({ name, size = 18, strokeWidth = 1.5, ...rest }: SwIconProps) {
  const Cmp = ICONS[name] ?? InfoCircle;
  return <Cmp width={size} height={size} strokeWidth={strokeWidth} color="currentColor" {...rest} />;
}

export default SwIcon;
